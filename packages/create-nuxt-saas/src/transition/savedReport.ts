import { lstat, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { z } from 'zod';
import { CliError } from '../errors';
import { changeNoteSchema, noteFileSchema, noteIdSchema } from '../kit/notes';
import type { Tree } from '../render/render';
import { JSON_SCHEMA, type JsonSavedReport, type JsonTransitionReport } from '../types/json';
import { hasSymbolicLink, pathExists, pruneEmptyDirectories, writeJsonAtomically, writeTextFile } from '../util/fs';
import { resolveInside } from '../util/paths';
import { missingNotes, suggestionLabel } from './noteText';

export const REPORT_PATH = '.nuxt-saas/upgrade-report.md';
const jsonPath = '.nuxt-saas/upgrade-report.json';
const kitVersionsPath = '.nuxt-saas/kit-versions';
const ignorePath = '.nuxt-saas/.gitignore';
const generatedIgnore = '# Generated by nuxt-saas\n*\n';

const resolutionAction = z.enum(['take-kit', 'combine', 'keep-mine']);
const backupSchema = z.object({
  ref: z.string(), name: z.string(), createdAt: z.string(), expiresAt: z.string(),
  status: z.enum(['pending', 'complete', 'failed', 'restored']),
});
const savedReportSchema = z.object({
  schema: z.literal(JSON_SCHEMA),
  from: z.string(),
  to: z.string(),
  changes: z.array(z.object({
    path: noteFileSchema,
    kind: z.enum(['create', 'update', 'merge', 'conflict', 'delete', 'keep-edited', 'keep-protected']),
  })),
  conflicts: z.array(noteFileSchema),
  followUps: z.array(z.string()),
  addedModules: z.array(z.string()),
  removedModules: z.array(z.string()),
  applied: z.boolean(),
  upToDate: z.boolean().optional(),
  unsaved: z.object({
    total: z.number(),
    risky: z.array(z.object({ path: noteFileSchema, kind: z.enum(['conflict', 'keep-edited']) })),
    touched: z.array(noteFileSchema),
    untouched: z.number(),
  }).nullable(),
  backup: backupSchema.nullable(),
  report: z.string().nullable(),
  notes: z.array(changeNoteSchema.extend({
    module: z.string(), outcome: z.enum(['applied', 'kept', 'conflict', 'declined']), affected: z.array(noteFileSchema),
  })).default([]),
  suggestions: z.array(z.object({
    path: noteFileSchema, action: z.enum(['take-kit', 'combine', 'keep-mine', 'by-hand']), reason: z.string(), notes: z.array(noteIdSchema),
  })).default([]),
  command: z.enum(['upgrade', 'add', 'remove']),
  createdAt: z.string(),
  fromVersion: z.string().nullable(),
  toVersion: z.string().nullable(),
  resolutions: z.array(z.object({ path: noteFileSchema, action: resolutionAction, at: z.string() })),
});

export async function readSavedReport(projectRoot: string): Promise<JsonSavedReport | null> {
  const path = join(projectRoot, jsonPath);
  if (!(await pathExists(path))) return null;
  await assertReportPaths(projectRoot);
  try {
    const report: unknown = JSON.parse(await readFile(path, 'utf8'));
    const { upToDate, ...rest } = savedReportSchema.parse(report);
    return { ...rest, ...(upToDate === undefined ? {} : { upToDate }) };
  } catch (error) {
    throw new CliError(`Unable to read ${jsonPath}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function kitCopyPath(projectRoot: string, path: string): Promise<string | null> {
  const absolute = resolveInside(join(projectRoot, kitVersionsPath), path, 'Kit version path');
  if (await hasSymbolicLink(projectRoot, absolute)) return null;
  try {
    return (await lstat(absolute)).isFile() ? absolute : null;
  } catch (error) {
    if (error instanceof Error && 'code' in error && (error.code === 'ENOENT' || error.code === 'ENOTDIR')) return null;
    throw error;
  }
}

export async function hasKitCopy(projectRoot: string, path: string): Promise<boolean> {
  return (await kitCopyPath(projectRoot, path)) !== null;
}

export async function readKitCopy(projectRoot: string, path: string): Promise<Buffer | null> {
  const absolute = await kitCopyPath(projectRoot, path);
  return absolute === null ? null : readFile(absolute);
}

export function reportGroups(report: Pick<JsonTransitionReport, 'changes' | 'conflicts'>) {
  const automatic = report.changes.filter(({ kind }) => kind === 'update' || kind === 'merge' || kind === 'delete').length;
  const kept = report.changes.filter(({ kind }) => kind === 'keep-edited').map(({ path }) => path);
  const created = report.changes.filter(({ kind }) => kind === 'create').length;
  return { automatic, conflicts: report.conflicts, kept, created };
}

export async function readKitVersion(kitRoot: string): Promise<string | null> {
  try {
    const value: unknown = JSON.parse(await readFile(join(kitRoot, 'package.json'), 'utf8'));
    if (value && typeof value === 'object' && 'version' in value && typeof value.version === 'string') {
      return value.version;
    }
  } catch {
    // A kit version is informational; missing or unreadable metadata is not fatal.
  }
  return null;
}

export function fileCount(count: number): string {
  return `${count} ${count === 1 ? 'file' : 'files'}`;
}

function renderMarkdown(report: JsonSavedReport): string {
  const { automatic, conflicts, kept, created } = reportGroups(report);
  const resolvedPaths = new Set(report.resolutions.map(({ path }) => path));
  const pending = conflicts.filter((path) => !resolvedPaths.has(path));
  const missing = missingNotes(report.notes, report.changes, true);
  const suggestions = new Map(report.suggestions.map((suggestion) => [suggestion.path, suggestion]));
  const from = report.fromVersion ?? report.from.slice(0, 7);
  const to = report.toVersion ?? report.to.slice(0, 7);
  const title = report.command === 'upgrade' ? `Kit ${from} → ${to}` : `Kit ${to} · Module ${report.command === 'add' ? 'addition' : 'removal'}`;
  return [
    `# ${title}`,
    '', report.createdAt, '',
    `- ✓ Applied automatically: ${fileCount(automatic)}`,
    `- ⚠ Needs your decision: ${fileCount(conflicts.length)}`,
    `- ↷ Kept your version: ${fileCount(kept.length)}`,
    `- + New files: ${created}`,
    ...(kept.length || missing.length ? ['', '## You may be missing', '',
      ...missing.map((note) => `- ${note}`),
      ...(kept.length ? ['', 'Your versions of these files were kept because you’d changed them, too.', '',
        ...kept.map((path) => `- ${JSON.stringify(path)}`)] : [])] : []),
    ...(pending.length ? ['', '## Needs your decision', '',
      ...pending.map((path) => {
        const suggestion = suggestions.get(path);
        return `- ${JSON.stringify(path)}${suggestion ? ` — **${suggestionLabel(suggestion.action)}.** ${suggestion.reason}` : ''}`;
      }), '', 'Next: `nuxt-saas resolve`'] : []),
    ...(report.resolutions.length ? ['', '## Resolutions', '',
      ...report.resolutions.map(({ path, action, at }) => `- ${JSON.stringify(path)} — ${suggestionLabel(action)} (${at})`)] : []),
    ...(report.backup ? ['', `Undo: \`nuxt-saas undo\` (backup kept until ${report.backup.expiresAt}).`] : []),
    ...(report.followUps.length ? ['', '## Follow-up steps', '', ...report.followUps.map((step) => `- ${step}`)] : []),
    '',
  ].join('\n');
}

export async function assertReportPaths(projectRoot: string): Promise<void> {
  for (const path of [jsonPath, REPORT_PATH, kitVersionsPath, ignorePath]) {
    const absolute = join(projectRoot, path);
    if (await hasSymbolicLink(projectRoot, absolute)) {
      throw new CliError(`Cannot use the upgrade report through a symbolic link: ${path}`);
    }
    try {
      const stats = await lstat(absolute);
      if (path === kitVersionsPath ? !stats.isDirectory() : !stats.isFile()) {
        throw new CliError(`Cannot use the upgrade report path: ${path}`);
      }
    } catch (error) {
      if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error;
    }
  }
}

export async function writeSavedReport(projectRoot: string, report: JsonSavedReport, target?: Tree): Promise<void> {
  await assertReportPaths(projectRoot);
  const ignore = join(projectRoot, ignorePath);
  if (!(await pathExists(ignore))) await writeTextFile(ignore, generatedIgnore);
  const rule = await readFile(ignore, 'utf8');
  if (!rule.split(/\r?\n/).includes('*')) {
    await writeTextFile(ignore, `${rule}${rule && !rule.endsWith('\n') ? '\n' : ''}*\n`);
  }
  if (target) {
    const versions = join(projectRoot, kitVersionsPath);
    await rm(versions, { recursive: true, force: true });
    for (const { path, kind } of report.changes) {
      if (kind !== 'conflict' && kind !== 'keep-edited') continue;
      const file = target.get(path);
      if (!file) continue; // The kit removed this path.
      const destination = resolveInside(versions, path, 'Kit version path');
      await mkdir(dirname(destination), { recursive: true });
      await writeFile(destination, file.content);
    }
  }
  await writeJsonAtomically(join(projectRoot, jsonPath), report);
  await writeTextFile(join(projectRoot, REPORT_PATH), renderMarkdown(report));
}

export async function removeReportFiles(projectRoot: string): Promise<void> {
  await assertReportPaths(projectRoot);
  await rm(join(projectRoot, REPORT_PATH), { force: true });
  await rm(join(projectRoot, jsonPath), { force: true });
  await rm(join(projectRoot, kitVersionsPath), { recursive: true, force: true });
  const ignore = join(projectRoot, ignorePath);
  if (await pathExists(ignore) && await readFile(ignore, 'utf8') === generatedIgnore) await rm(ignore);
  await pruneEmptyDirectories(projectRoot, join(projectRoot, '.nuxt-saas'));
}
