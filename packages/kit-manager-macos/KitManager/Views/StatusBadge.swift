import KitManagerCore
import SwiftUI

struct StatusBadge: View {
    let status: ProjectStatus
    /// True while the kit has never been fetched, so "checking" really means "offline".
    var isOffline = false

    @Environment(\.accessibilityReduceTransparency) private var reduceTransparency

    private enum Tone {
        case amber, red, green, grey

        var color: Color {
            switch self {
            case .amber: Theme.amber
            case .red: Theme.red
            case .green: Theme.green
            case .grey: Theme.grey
            }
        }
    }

    private struct Appearance {
        let title: String
        let detail: String?
        let symbol: String?
        let tone: Tone
        let help: String
    }

    var body: some View {
        let look = appearance
        let content = HStack(spacing: 6) {
            if let symbol = look.symbol {
                Image(systemName: symbol)
                    .foregroundStyle(look.tone.color)
                    .imageScale(.small)
            } else {
                ProgressView().controlSize(.mini)
            }
            VStack(alignment: .leading, spacing: 0) {
                Text(look.title)
                    .font(.callout.weight(.medium))
                if let detail = look.detail {
                    Text(detail)
                        .font(.caption2)
                        .foregroundStyle(.secondary)
                }
            }
        }
        .lineLimit(1)
        .padding(.horizontal, 8)
        .padding(.vertical, 3)

        Group {
            if reduceTransparency {
                content
                    .background(look.tone.color.opacity(0.16), in: .rect(cornerRadius: Theme.radius))
                    .overlay {
                        RoundedRectangle(cornerRadius: Theme.radius)
                            .strokeBorder(look.tone.color.opacity(0.45), lineWidth: 0.5)
                    }
            } else {
                content
                    .glassEffect(.regular.tint(look.tone.color.opacity(0.22)), in: .rect(cornerRadius: Theme.radius))
            }
        }
        .help(look.help)
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(look.help)
    }

    private var appearance: Appearance {
        switch status {
        case .missing:
            Appearance(
                title: "Missing", detail: nil, symbol: "questionmark.folder", tone: .red,
                help: "Missing: the folder was moved or deleted")
        case .invalid(let reason):
            Appearance(title: "Invalid state", detail: nil, symbol: "xmark.octagon", tone: .red, help: reason)
        case .needsMigration(let source):
            switch source {
            case .legacy:
                Appearance(
                    title: "Needs migration", detail: "kit 2.x", symbol: "arrow.triangle.branch", tone: .grey,
                    help: "Needs migration: generated by create-nuxt-saas 2.x")
            case .nuxt:
                Appearance(
                    title: "Needs migration", detail: "plain Nuxt", symbol: "arrow.triangle.branch", tone: .grey,
                    help: "Needs migration: a Nuxt project that does not use the kit")
            case .other:
                Appearance(
                    title: "Not a Nuxt project", detail: nil, symbol: "minus.circle", tone: .grey,
                    help: "Not a Nuxt project")
            }
        case .unresolvedConflicts(let count):
            Appearance(
                title: count == 1 ? "1 conflict" : "\(count) conflicts", detail: "unresolved",
                symbol: "exclamationmark.triangle.fill", tone: .red,
                help: "\(count) unresolved merge conflicts from a previous upgrade")
        case .otherTemplate:
            Appearance(
                title: "Other template", detail: nil, symbol: "square.on.square", tone: .grey,
                help: "Other template: generated from a fork or another ref, so there is no version to compare")
        case .commitNotOnMain(let shortSHA):
            Appearance(
                title: "Not on main", detail: shortSHA, symbol: "questionmark.circle", tone: .grey,
                help: "Kit commit \(shortSHA) is not on main in your kit checkout")
        case .upToDate:
            Appearance(
                title: "Up to date", detail: nil, symbol: "checkmark.circle.fill", tone: .green,
                help: "Up to date with the latest kit")
        case .behind(let count, let preview):
            Appearance(
                title: "\(count) behind", detail: detail(of: preview), symbol: "arrow.down.circle.fill",
                tone: .amber, help: "\(count) kit commits behind. \(help(for: preview))")
        case .checkFailed(let message):
            Appearance(
                title: "Check failed", detail: nil, symbol: "exclamationmark.circle", tone: .grey,
                help: "Could not compare with the latest kit: \(message)")
        case .checking:
            if isOffline {
                Appearance(
                    title: "Offline", detail: "no kit fetched", symbol: "wifi.slash", tone: .grey,
                    help: "Offline: the kit has not been fetched yet")
            } else {
                Appearance(title: "Checking", detail: nil, symbol: nil, tone: .grey, help: "Checking status")
            }
        }
    }

    private func detail(of preview: UpgradePreview) -> String? {
        switch preview {
        case .pending: "previewing"
        case .ready(let summary, let stale): stale ? "\(upgradeCost(summary)), stale" : upgradeCost(summary)
        case .failed: "preview failed"
        }
    }

    private func help(for preview: UpgradePreview) -> String {
        switch preview {
        case .pending: "Upgrade preview is being computed."
        case .ready(let summary, let stale):
            "Upgrade: \(upgradeCost(summary))\(stale ? ". This preview is out of date and is being recomputed." : ".")"
        case .failed(let message): "The upgrade preview failed: \(message)"
        }
    }

    /// "clean", "3 merges" or "2 conflicts".
    private func upgradeCost(_ summary: PreviewSummary) -> String {
        if summary.conflicts > 0 { return summary.conflicts == 1 ? "1 conflict" : "\(summary.conflicts) conflicts" }
        let merges = summary.counts[.merge, default: 0]
        if merges > 0 { return merges == 1 ? "1 merge" : "\(merges) merges" }
        return "clean"
    }
}
